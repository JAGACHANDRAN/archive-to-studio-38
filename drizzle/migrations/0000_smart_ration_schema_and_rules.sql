create or replace function public._next_id(_prefix text)
returns text language plpgsql security definer set search_path = public as $$
begin
  if _prefix = 'MOV' then return 'MOV-' || lpad(nextval('public.mov_seq')::text, 6, '0'); end if;
  if _prefix = 'DEL' then return 'DEL-' || lpad(nextval('public.del_seq')::text, 5, '0'); end if;
  if _prefix = 'ALT' then return 'ALT-' || lpad(nextval('public.alert_seq')::text, 5, '0'); end if;
  if _prefix = 'MEA' then return 'MEA-' || lpad(nextval('public.mea_seq')::text, 4, '0'); end if;
  raise exception 'Unknown id prefix %', _prefix;
end $$;

