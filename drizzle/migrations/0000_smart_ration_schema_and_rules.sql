-- ================= Derived stock =================
create or replace function public.godown_stock(_godown_id text, _as_of timestamptz default null)
returns numeric language sql stable set search_path = public as $$
  select round(g.opening_stock_kg + coalesce(sum(case m.movement_type
      when 'RECEIPT' then m.quantity_kg
      when 'DISPATCH' then -m.quantity_kg
      when 'ADJUSTMENT' then m.quantity_kg else 0 end), 0), 2)
  from public.godowns g
  left join public.stock_movements m
    on m.location_type = 'godown' and m.location_id = g.id and (_as_of is null or m."timestamp" <= _as_of)
  where g.id = _godown_id
  group by g.opening_stock_kg
$$;

create or replace function public.shop_stock(_shop_id text, _as_of timestamptz default null)
returns numeric language sql stable set search_path = public as $$
  select round(s.opening_stock_kg + coalesce(sum(case m.movement_type
      when 'CONFIRMED_DELIVERY' then m.quantity_kg
      when 'DISTRIBUTION' then -m.quantity_kg
      when 'ADJUSTMENT' then m.quantity_kg else 0 end), 0), 2)
  from public.shops s
  left join public.stock_movements m
    on m.location_type = 'shop' and m.location_id = s.id and (_as_of is null or m."timestamp" <= _as_of)
  where s.id = _shop_id
  group by s.opening_stock_kg
$$;

create or replace function public.shop_avg_monthly(_shop_id text)
returns numeric language sql stable set search_path = public as $$
  select round(coalesce(avg(distributed_qty_kg), 0), 2) from public.monthly_distribution where shop_id = _shop_id
$$;

create or replace function public.stock_status(_stock numeric, _avg numeric)
returns text language sql immutable set search_path = public as $$
  select case when _stock < _avg * 0.10 then 'CRITICAL' when _stock < _avg * 0.20 then 'LOW' else 'NORMAL' end
$$;

create view public.v_godown_stock with (security_invoker = true) as
select g.id, g.code, g.name, g.district_id, g.capacity_kg, g.opening_stock_kg, g.lat, g.lng,
  coalesce(mv.receipts, 0) as receipts_kg,
  coalesce(mv.dispatches, 0) as dispatches_kg,
  coalesce(mv.adjustments, 0) as adjustments_kg,
  round(g.opening_stock_kg + coalesce(mv.receipts, 0) - coalesce(mv.dispatches, 0) + coalesce(mv.adjustments, 0), 2) as expected_stock_kg,
  case when g.capacity_kg > 0 then round((g.opening_stock_kg + coalesce(mv.receipts, 0) - coalesce(mv.dispatches, 0) + coalesce(mv.adjustments, 0)) / g.capacity_kg * 100, 2) else 0 end as utilization_pct
from public.godowns g
left join lateral (
  select sum(quantity_kg) filter (where movement_type = 'RECEIPT') as receipts,
         sum(quantity_kg) filter (where movement_type = 'DISPATCH') as dispatches,
         sum(quantity_kg) filter (where movement_type = 'ADJUSTMENT') as adjustments
  from public.stock_movements m where m.location_type = 'godown' and m.location_id = g.id
) mv on true;

create view public.v_shop_stock with (security_invoker = true) as
select x.*,
  round(x.avg_monthly_dist_kg * 0.20, 2) as low_stock_threshold_kg,
  round(x.avg_monthly_dist_kg * 0.10, 2) as critical_threshold_kg,
  public.stock_status(x.expected_stock_kg, x.avg_monthly_dist_kg) as status
from (
  select s.id, s.code, s.name, s.district_id, s.godown_id, s.beneficiaries_count, s.card_count, s.opening_stock_kg, s.lat, s.lng,
    coalesce(mv.confirmed, 0) as confirmed_deliveries_kg,
    coalesce(mv.distributed, 0) as distributions_kg,
    coalesce(mv.adjustments, 0) as adjustments_kg,
    round(s.opening_stock_kg + coalesce(mv.confirmed, 0) - coalesce(mv.distributed, 0) + coalesce(mv.adjustments, 0), 2) as expected_stock_kg,
    round(coalesce(md.avg_dist, 0), 2) as avg_monthly_dist_kg
  from public.shops s
  left join lateral (
    select sum(quantity_kg) filter (where movement_type = 'CONFIRMED_DELIVERY') as confirmed,
           sum(quantity_kg) filter (where movement_type = 'DISTRIBUTION') as distributed,
           sum(quantity_kg) filter (where movement_type = 'ADJUSTMENT') as adjustments
    from public.stock_movements m where m.location_type = 'shop' and m.location_id = s.id
  ) mv on true
  left join lateral (select avg(distributed_qty_kg) as avg_dist from public.monthly_distribution d where d.shop_id = s.id) md on true
) x;

create view public.v_measurement_reconciliation with (security_invoker = true) as
select y.*,
  y.difference_pct > 2.0 as discrepancy_detected,
  2.0::numeric as tolerance_pct,
  case when y.difference_pct > 2.0 then 'Verification requested on stock balance' else 'Verified within normal tolerance' end as status_label
from (
  select z.*,
    round(z.measured_stock_kg - z.expected_stock_kg, 2) as difference_kg,
    case when z.expected_stock_kg > 0 then round(abs(z.measured_stock_kg - z.expected_stock_kg) / z.expected_stock_kg * 100, 2) else 0 end as difference_pct
  from (
    select m.id as measurement_id, m.location_type, m.location_id, m.measured_date, m.measured_stock_kg, m.inspector_name, m.remarks,
      coalesce(g.name, s.name, m.location_id) as location_label,
      coalesce(g.district_id, s.district_id) as district_id,
      case when m.location_type = 'godown' then public.godown_stock(m.location_id, m.measured_date)
           else public.shop_stock(m.location_id, m.measured_date) end as expected_stock_kg
    from public.measurements m
    left join public.godowns g on m.location_type = 'godown' and g.id = m.location_id
    left join public.shops s on m.location_type = 'shop' and s.id = m.location_id
  ) z
) y;

