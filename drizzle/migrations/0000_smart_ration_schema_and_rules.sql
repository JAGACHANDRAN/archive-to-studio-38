create or replace function public._actor_username()
returns text language sql stable security definer set search_path = public as $$
  select coalesce((select username from public.profiles where id = auth.uid()), 'system')
$$;

create or replace function public._require_roles(_allowed public.app_role[])
returns public.user_roles language plpgsql stable security definer set search_path = public as $$
declare r public.user_roles;
begin
  if auth.uid() is null then
    raise exception 'Authentication required. Please sign in.' using errcode = '28000';
  end if;
  select * into r from public.user_roles where user_id = auth.uid() order by role limit 1;
  if r.id is null then
    raise exception 'Forbidden: your account has no assigned role.' using errcode = '42501';
  end if;
  if not (r.role = any(_allowed)) then
    raise exception 'Forbidden: Role ''%'' is not authorized for this operation. Required: %', r.role, _allowed using errcode = '42501';
  end if;
  return r;
end $$;

create or replace function public._check_location_access(_r public.user_roles, _loc_type text, _loc_id text, _action text)
returns void language plpgsql stable security definer set search_path = public as $$
declare v_uname text := public._actor_username(); v_shop public.shops; v_godown public.godowns;
begin
  if _r.role in ('state_admin', 'stock_inspector') then return; end if;
  if _r.role = 'shop_manager' then
    if _loc_type <> 'shop' or _loc_id is distinct from _r.shop_id then
      raise exception 'Access Denied: Shop Manager ''%'' is assigned to shop ''%'' and cannot % % ''%''.', v_uname, _r.shop_id, _action, _loc_type, _loc_id using errcode = '42501';
    end if;
    return;
  end if;
  if _r.role = 'godown_manager' then
    if _loc_type = 'godown' then
      if _loc_id is distinct from _r.godown_id then
        raise exception 'Access Denied: Godown Manager ''%'' is assigned to ''%'' and cannot % godown ''%''.', v_uname, _r.godown_id, _action, _loc_id using errcode = '42501';
      end if;
      return;
    elsif _loc_type = 'shop' then
      select * into v_shop from public.shops where id = _loc_id;
      if v_shop.id is null or v_shop.godown_id is distinct from _r.godown_id then
        raise exception 'Access Denied: Shop ''%'' is not linked to godown ''%''.', _loc_id, _r.godown_id using errcode = '42501';
      end if;
      return;
    end if;
    raise exception 'Access Denied: Godown Manager cannot % district-level records.', _action using errcode = '42501';
  end if;
  if _r.role in ('district_officer', 'data_entry_officer') then
    if _r.district_id is null then return; end if;
    if _loc_type = 'district' then
      if _loc_id::integer <> _r.district_id then
        raise exception 'Access Denied: assigned to District % and cannot % District %.', _r.district_id, _action, _loc_id using errcode = '42501';
      end if;
    elsif _loc_type = 'godown' then
      select * into v_godown from public.godowns where id = _loc_id;
      if v_godown.id is null or v_godown.district_id <> _r.district_id then
        raise exception 'Access Denied: Godown ''%'' does not belong to District %.', _loc_id, _r.district_id using errcode = '42501';
      end if;
    elsif _loc_type = 'shop' then
      select * into v_shop from public.shops where id = _loc_id;
      if v_shop.id is null or v_shop.district_id <> _r.district_id then
        raise exception 'Access Denied: Shop ''%'' does not belong to District %.', _loc_id, _r.district_id using errcode = '42501';
      end if;
    end if;
    return;
  end if;
end $$;

