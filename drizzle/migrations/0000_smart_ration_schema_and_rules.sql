create or replace function public.monthly_report_rows(_month text)
returns table (
  shop_id text, shop_name text, district_id integer, district_name text, district_code text, godown_id text,
  beneficiaries_count integer, opening_stock_kg numeric, received_kg numeric, distributed_kg numeric,
  prev_distributed_kg numeric, mom_diff_kg numeric, mom_pct numeric, closing_stock_kg numeric, status text
) language sql stable set search_path = public as $$
  with bounds as (
    select to_date(_month, 'YYYY-MM')::timestamptz as m_start,
           (to_date(_month, 'YYYY-MM') + interval '1 month')::timestamptz as m_end,
           to_char(to_date(_month, 'YYYY-MM') - interval '1 month', 'YYYY-MM') as prev_month
  ), base as (
    select s.id, s.name, s.district_id, d.name as dname, d.code as dcode, s.godown_id, s.beneficiaries_count,
      round(coalesce((select sum(quantity_kg) from public.stock_movements m, bounds b
        where m.location_type = 'shop' and m.location_id = s.id and m.movement_type = 'CONFIRMED_DELIVERY'
          and m."timestamp" >= b.m_start and m."timestamp" < b.m_end), 0), 2) as rcv,
      round(coalesce((select sum(distributed_qty_kg) from public.monthly_distribution md where md.shop_id = s.id and md.month_year = _month), 0), 2) as dist,
      round(coalesce((select sum(distributed_qty_kg) from public.monthly_distribution md, bounds b where md.shop_id = s.id and md.month_year = b.prev_month), 0), 2) as prev,
      public.shop_stock(s.id, (select m_end from bounds)) as closing,
      public.shop_avg_monthly(s.id) as avg_dist
    from public.shops s join public.districts d on d.id = s.district_id
  )
  select id, name, district_id, dname, dcode, godown_id, beneficiaries_count,
    round(closing - rcv + dist, 2), rcv, dist, prev, round(dist - prev, 2),
    case when prev > 0 then round((dist - prev) / prev * 100, 1) else 0 end,
    closing, public.stock_status(closing, avg_dist)
  from base order by id
$$;

grant execute on function public.godown_stock(text, timestamptz), public.shop_stock(text, timestamptz),
  public.shop_avg_monthly(text), public.stock_status(numeric, numeric), public.monthly_report_rows(text)
  to anon, authenticated, service_role;

