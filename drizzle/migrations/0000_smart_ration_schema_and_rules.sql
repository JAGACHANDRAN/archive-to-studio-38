create or replace function public.ingest_transaction(_shop_id text, _qty_kg numeric, _card_no text, _item_id integer default 1,
  _bags integer default 1, _source text default 'simulator', _ts timestamptz default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare s public.shops; c public.commodities; v_txn text; v_ts timestamptz := coalesce(_ts, now()); v_remaining numeric; v_alert jsonb; v_alert_id text;
begin
  perform public._ingest_allowed();
  select * into s from public.shops where id = _shop_id for update;
  if s.id is null then raise exception 'Shop ''%'' not found in registry.', _shop_id using errcode = 'P0002'; end if;
  if _qty_kg is null or _qty_kg <= 0 then raise exception 'qty_kg must be positive'; end if;
  if _card_no is null or length(_card_no) < 4 then raise exception 'card_no is required'; end if;
  if _source not in ('simulator', 'sensor', 'ml_camera') then raise exception 'Unknown source %', _source; end if;
  select * into c from public.commodities where id = coalesce(_item_id, 1);
  if c.id is null then select * into c from public.commodities where id = 1; end if;
  v_txn := 'TXN-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10));
  insert into public.transactions(id, shop_id, item_id, qty_kg, bags, card_no, source, "timestamp")
  values (v_txn, s.id, c.id, _qty_kg, greatest(coalesce(_bags, 1), 1), _card_no, _source, v_ts);
  insert into public.stock_movements(id, location_type, location_id, movement_type, quantity_kg, "timestamp", reference_id, created_by)
  values (public._next_id('MOV'), 'shop', s.id, 'DISTRIBUTION', _qty_kg, v_ts, v_txn, _source);
  v_remaining := public.shop_stock(s.id);
  insert into public.stock_levels(location_type, location_id, item_id, qty_kg, updated_at, source)
  values ('shop', s.id, c.id, greatest(v_remaining, 0), v_ts, _source)
  on conflict (location_type, location_id, item_id) do update set qty_kg = excluded.qty_kg, updated_at = excluded.updated_at, source = excluded.source;
  if v_remaining < 300 and not exists (select 1 from public.alerts where location_type = 'shop' and location_id = s.id and alert_type = 'LOW_STOCK' and status = 'OPEN') then
    v_alert_id := public._next_id('ALT');
    insert into public.alerts(id, location_type, location_id, item_id, alert_type, severity, "timestamp", explanation, assigned_role)
    values (v_alert_id, 'shop', s.id, c.id, 'LOW_STOCK', case when v_remaining < 150 then 'CRITICAL' else 'HIGH' end, v_ts,
      format('Critical stock exhaustion: %s kg of %s remaining.', round(v_remaining, 1), c.name), 'shop_manager');
    v_alert := jsonb_build_object('id', v_alert_id, 'type', 'LOW_STOCK');
  end if;
  return jsonb_build_object('status', 'success', 'transaction_id', v_txn, 'shop_id', s.id, 'item_id', c.id, 'item_name', c.name,
    'qty_kg', _qty_kg, 'bags', greatest(coalesce(_bags, 1), 1), 'card_no', _card_no, 'remaining_stock_kg', round(v_remaining, 2),
    'source', _source, 'timestamp', v_ts, 'alert_triggered', v_alert);
end $$;

create or replace function public.ingest_stock(_location_type text, _location_id text, _qty_kg numeric, _item_id integer default 1,
  _source text default 'sensor', _ts timestamptz default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_prev public.stock_levels; v_ts timestamptz := coalesce(_ts, now()); v_diff numeric; v_anomaly boolean := false; v_alert jsonb; v_alert_id text; v_exists boolean;
begin
  perform public._ingest_allowed();
  if _location_type not in ('godown', 'shop') then raise exception 'location_type must be godown or shop'; end if;
  if _qty_kg is null or _qty_kg < 0 then raise exception 'qty_kg must be zero or positive'; end if;
  if _source not in ('simulator', 'sensor', 'ml_camera') then raise exception 'Unknown source %', _source; end if;
  if _location_type = 'godown' then select exists(select 1 from public.godowns where id = _location_id) into v_exists;
  else select exists(select 1 from public.shops where id = _location_id) into v_exists; end if;
  if not v_exists then raise exception 'Location ''%'' not found', _location_id using errcode = 'P0002'; end if;
  select * into v_prev from public.stock_levels where location_type = _location_type and location_id = _location_id and item_id = coalesce(_item_id, 1) for update;
  if v_prev.id is not null then
    v_diff := v_prev.qty_kg - _qty_kg;
    if v_diff >= 500 or (v_prev.qty_kg > 0 and v_diff / v_prev.qty_kg >= 0.20) then
      v_anomaly := true;
      select jsonb_build_object('id', id, 'type', alert_type, 'status', 'existing') into v_alert from public.alerts
        where location_type = _location_type and location_id = _location_id and alert_type = 'STOCK_DISCREPANCY' and status = 'OPEN' limit 1;
      if v_alert is null then
        v_alert_id := public._next_id('ALT');
        insert into public.alerts(id, location_type, location_id, item_id, alert_type, severity, "timestamp", explanation, assigned_role)
        values (v_alert_id, _location_type, _location_id, coalesce(_item_id, 1), 'STOCK_DISCREPANCY', 'CRITICAL', v_ts,
          format('Verification requested on stock balance: Unexplained stock reduction of %s kg detected.', to_char(v_diff, 'FM999,999,990.0')),
          case when _location_type = 'godown' then 'district_officer' else 'shop_manager' end);
        v_alert := jsonb_build_object('id', v_alert_id, 'type', 'STOCK_DISCREPANCY');
      end if;
    end if;
  end if;
  insert into public.stock_levels(location_type, location_id, item_id, qty_kg, updated_at, source)
  values (_location_type, _location_id, coalesce(_item_id, 1), _qty_kg, v_ts, _source)
  on conflict (location_type, location_id, item_id) do update set qty_kg = excluded.qty_kg, updated_at = excluded.updated_at, source = excluded.source;
  return jsonb_build_object('status', 'success', 'location_type', _location_type, 'location_id', _location_id, 'updated_stock_kg', round(_qty_kg, 2),
    'source', _source, 'timestamp', v_ts, 'anomaly_detected', v_anomaly, 'alert_triggered', v_alert);
end $$;

create or replace function public.activate_data_source(_source_name text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r public.user_roles;
begin
  r := public._require_roles(array['state_admin']::public.app_role[]);
  if _source_name not in ('simulator', 'sensor', 'ml_camera') then raise exception 'Unknown source %', _source_name; end if;
  update public.data_source_settings set is_active = (source_name = _source_name), updated_at = now();
  perform public._log_audit('ACTIVATE_DATA_SOURCE', 'SYSTEM', _source_name, format('Active data source set to %s.', _source_name));
  return jsonb_build_object('active_source', _source_name);
end $$;

-- ================= New user -> profile + role mapping =================
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare d public.demo_accounts;
begin
  select * into d from public.demo_accounts where lower(email) = lower(new.email);
  insert into public.profiles(id, legacy_user_id, username, email, full_name)
  values (new.id, d.legacy_user_id, coalesce(d.username, split_part(new.email, '@', 1)), new.email, coalesce(d.full_name, new.raw_user_meta_data->>'full_name', new.email))
  on conflict (id) do nothing;
  if d.legacy_user_id is not null then
    insert into public.user_roles(user_id, role, district_id, godown_id, shop_id)
    values (new.id, d.role, d.district_id, d.godown_id, d.shop_id)
    on conflict (user_id, role) do nothing;
  end if;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

