create or replace function public.record_receipt(_godown_id text, _quantity_kg numeric, _reference_id text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r public.user_roles; g public.godowns; v_mov text; v_stock numeric;
begin
  r := public._require_roles(array['state_admin','godown_manager']::public.app_role[]);
  perform public._check_location_access(r, 'godown', _godown_id, 'record receipt for');
  select * into g from public.godowns where id = _godown_id for update;
  if g.id is null then raise exception 'Godown ''%'' not found', _godown_id; end if;
  if _quantity_kg is null or _quantity_kg <= 0 then raise exception 'Receipt quantity must be positive kg'; end if;
  v_mov := public._next_id('MOV');
  insert into public.stock_movements(id, location_type, location_id, movement_type, quantity_kg, reference_id, created_by)
  values (v_mov, 'godown', g.id, 'RECEIPT', round(_quantity_kg, 2), nullif(trim(coalesce(_reference_id, '')), ''), public._actor_username());
  v_stock := public.godown_stock(g.id);
  perform public._log_audit('RECORD_RECEIPT', 'GODOWN', g.id,
    format('Received %s kg into %s. Ref: %s. New stock: %s kg.', round(_quantity_kg, 2), g.id, coalesce(_reference_id, '-'), v_stock));
  return jsonb_build_object('movement_id', v_mov, 'godown_id', g.id, 'new_expected_stock_kg', v_stock,
    'message', format('Recorded receipt of %s kg at %s.', round(_quantity_kg, 2), g.name));
end $$;

create or replace function public.create_dispatch(_godown_id text, _shop_id text, _quantity_kg numeric,
  _expected_delivery_date timestamptz default null, _notes text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r public.user_roles; g public.godowns; s public.shops; v_stock numeric; v_mov text; v_del text; v_eta timestamptz;
begin
  r := public._require_roles(array['state_admin','godown_manager']::public.app_role[]);
  perform public._check_location_access(r, 'godown', _godown_id, 'dispatch from');
  select * into g from public.godowns where id = _godown_id for update;
  if g.id is null then raise exception 'Godown ''%'' not found', _godown_id; end if;
  select * into s from public.shops where id = _shop_id;
  if s.id is null then raise exception 'Shop ''%'' not found', _shop_id; end if;
  if _quantity_kg is null or _quantity_kg <= 0 then raise exception 'Dispatch quantity must be positive kg'; end if;
  v_stock := public.godown_stock(g.id);
  if _quantity_kg > v_stock then
    raise exception 'Over-dispatch rejected: requested % kg exceeds available stock of % kg at %.', round(_quantity_kg, 2), v_stock, g.name;
  end if;
  v_del := public._next_id('DEL');
  v_mov := public._next_id('MOV');
  v_eta := coalesce(_expected_delivery_date, now() + interval '28 hours');
  insert into public.stock_movements(id, location_type, location_id, movement_type, quantity_kg, reference_id, created_by)
  values (v_mov, 'godown', g.id, 'DISPATCH', round(_quantity_kg, 2), v_del, public._actor_username());
  insert into public.deliveries(id, dispatch_movement_id, from_godown_id, to_shop_id, dispatched_date, expected_delivery_date, status, dispatched_qty_kg, received_qty_kg, notes)
  values (v_del, v_mov, g.id, s.id, now(), v_eta, 'PENDING', round(_quantity_kg, 2), 0, coalesce(nullif(trim(coalesce(_notes, '')), ''), 'Consignment in transit'));
  v_stock := public.godown_stock(g.id);
  perform public._log_audit('CREATE_DISPATCH', 'DELIVERY', v_del,
    format('Dispatched %s kg from %s to %s. Delivery ID: %s. Godown stock: %s kg.', round(_quantity_kg, 2), g.id, s.id, v_del, v_stock));
  return jsonb_build_object('delivery_id', v_del, 'dispatch_movement_id', v_mov, 'godown_remaining_stock_kg', v_stock,
    'expected_delivery_date', v_eta, 'message', format('Consignment %s created for %s kg to %s.', v_del, round(_quantity_kg, 2), s.name));
end $$;

create or replace function public.confirm_delivery(_delivery_id text, _received_qty_kg numeric, _notes text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r public.user_roles; d public.deliveries; v_diff numeric; v_status text; v_mov text; v_stock numeric;
begin
  r := public._require_roles(array['state_admin','shop_manager','godown_manager']::public.app_role[]);
  select * into d from public.deliveries where id = _delivery_id for update;
  if d.id is null then raise exception 'Delivery ''%'' not found', _delivery_id; end if;
  perform public._check_location_access(r, 'shop', d.to_shop_id, 'confirm delivery for');
  if d.status in ('DELIVERED', 'RECEIVED_WITH_DIFFERENCE') then
    raise exception 'Consignment % has already been confirmed as received.', d.id;
  end if;
  if _received_qty_kg is null or _received_qty_kg <= 0 then raise exception 'Received quantity must be positive kg'; end if;
  v_diff := round(_received_qty_kg - d.dispatched_qty_kg, 2);
  v_status := case when abs(v_diff) > 0.001 then 'RECEIVED_WITH_DIFFERENCE' else 'DELIVERED' end;
  update public.deliveries set status = v_status, received_qty_kg = round(_received_qty_kg, 2), received_date = now(),
    notes = case when nullif(trim(coalesce(_notes, '')), '') is null then notes else trim(both ' |' from coalesce(notes, '') || ' | Note: ' || trim(_notes)) end
  where id = d.id;
  v_mov := public._next_id('MOV');
  insert into public.stock_movements(id, location_type, location_id, movement_type, quantity_kg, reference_id, created_by)
  values (v_mov, 'shop', d.to_shop_id, 'CONFIRMED_DELIVERY', round(_received_qty_kg, 2), d.id, public._actor_username());
  v_stock := public.shop_stock(d.to_shop_id);
  perform public._log_audit('CONFIRM_DELIVERY', 'DELIVERY', d.id,
    format('Confirmed delivery %s at %s: received %s kg of %s kg dispatched%s. Shop stock: %s kg.', d.id, d.to_shop_id,
      round(_received_qty_kg, 2), d.dispatched_qty_kg,
      case when v_status = 'RECEIVED_WITH_DIFFERENCE' then format(' (Variance: %s kg, Status: %s)', v_diff, v_status) else '' end, v_stock));
  return jsonb_build_object('delivery_id', d.id, 'movement_id', v_mov, 'delivery_status', v_status,
    'has_difference', v_status = 'RECEIVED_WITH_DIFFERENCE', 'difference_kg', v_diff, 'shop_new_expected_stock_kg', v_stock,
    'message', format('Consignment %s confirmed with status ''%s''.', d.id, replace(v_status, '_', ' ')));
end $$;

create or replace function public.record_distribution(_shop_id text, _quantity_kg numeric, _beneficiary_households integer default 0, _reference_id text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r public.user_roles; s public.shops; v_stock numeric; v_mov text; v_ref text; v_month text := to_char(now() at time zone 'UTC', 'YYYY-MM');
begin
  r := public._require_roles(array['state_admin','shop_manager','data_entry_officer']::public.app_role[]);
  perform public._check_location_access(r, 'shop', _shop_id, 'record distribution for');
  select * into s from public.shops where id = _shop_id for update;
  if s.id is null then raise exception 'Shop ''%'' not found', _shop_id; end if;
  if _quantity_kg is null or _quantity_kg <= 0 then raise exception 'Distribution quantity must be positive kg'; end if;
  if coalesce(_beneficiary_households, 0) < 0 then raise exception 'Beneficiary households cannot be negative'; end if;
  v_stock := public.shop_stock(s.id);
  if _quantity_kg > v_stock then
    raise exception 'Over-distribution rejected: requested % kg exceeds available stock of % kg at %.', round(_quantity_kg, 2), v_stock, s.name;
  end if;
  v_mov := public._next_id('MOV');
  v_ref := coalesce(nullif(trim(coalesce(_reference_id, '')), ''), 'POS-TX-' || to_char(now() at time zone 'UTC', 'YYYYMMDDHH24MI') || '-' || s.id);
  insert into public.stock_movements(id, location_type, location_id, movement_type, quantity_kg, reference_id, created_by)
  values (v_mov, 'shop', s.id, 'DISTRIBUTION', round(_quantity_kg, 2), v_ref, public._actor_username());
  insert into public.monthly_distribution as md (shop_id, month_year, distributed_qty_kg, beneficiary_households_served)
  values (s.id, v_month, round(_quantity_kg, 2), coalesce(_beneficiary_households, 0))
  on conflict (shop_id, month_year) do update set
    distributed_qty_kg = round(md.distributed_qty_kg + excluded.distributed_qty_kg, 2),
    beneficiary_households_served = md.beneficiary_households_served + excluded.beneficiary_households_served;
  v_stock := public.shop_stock(s.id);
  perform public._log_audit('RECORD_DISTRIBUTION', 'SHOP', s.id,
    format('Distributed %s kg to %s cardholders at %s. Ref: %s. New stock: %s kg.', round(_quantity_kg, 2), coalesce(_beneficiary_households, 0), s.id, v_ref, v_stock));
  return jsonb_build_object('movement_id', v_mov, 'shop_remaining_stock_kg', v_stock,
    'message', format('Recorded distribution of %s kg at %s.', round(_quantity_kg, 2), s.name));
end $$;

create or replace function public.record_adjustment(_location_type text, _location_id text, _quantity_kg numeric, _reason text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r public.user_roles; v_name text; v_stock numeric; v_mov text;
begin
  r := public._require_roles(array['state_admin','district_officer','godown_manager','shop_manager']::public.app_role[]);
  if _reason is null or trim(_reason) = '' then raise exception 'Adjustment reason is strictly mandatory'; end if;
  if _location_type not in ('godown', 'shop') then raise exception 'Location type must be godown or shop'; end if;
  perform public._check_location_access(r, _location_type, _location_id, 'apply adjustment to');
  if _location_type = 'godown' then
    select name into v_name from public.godowns where id = _location_id for update;
    if v_name is null then raise exception 'Godown ''%'' not found', _location_id; end if;
    v_stock := public.godown_stock(_location_id);
  else
    select name into v_name from public.shops where id = _location_id for update;
    if v_name is null then raise exception 'Shop ''%'' not found', _location_id; end if;
    v_stock := public.shop_stock(_location_id);
  end if;
  if _quantity_kg is null or _quantity_kg = 0 then raise exception 'Adjustment quantity cannot be zero'; end if;
  if _quantity_kg < 0 and abs(_quantity_kg) > v_stock then
    raise exception 'Adjustment rejected: deduction of % kg exceeds available balance of % kg at %.', abs(round(_quantity_kg, 2)), v_stock, v_name;
  end if;
  v_mov := public._next_id('MOV');
  insert into public.stock_movements(id, location_type, location_id, movement_type, quantity_kg, reference_id, created_by)
  values (v_mov, _location_type, _location_id, 'ADJUSTMENT', round(_quantity_kg, 2), 'REASON: ' || trim(_reason), public._actor_username());
  v_stock := case when _location_type = 'godown' then public.godown_stock(_location_id) else public.shop_stock(_location_id) end;
  perform public._log_audit('RECORD_ADJUSTMENT', upper(_location_type), _location_id,
    format('Stock adjustment of %s kg at %s. Reason: %s. Resulting balance: %s kg.', round(_quantity_kg, 2), _location_id, trim(_reason), v_stock));
  return jsonb_build_object('movement_id', v_mov, 'new_expected_stock_kg', v_stock,
    'message', format('Applied adjustment of %s kg to %s.', round(_quantity_kg, 2), v_name));
end $$;

create or replace function public.record_measurement(_location_type text, _location_id text, _measured_stock_kg numeric, _remarks text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r public.user_roles; v_name text; v_expected numeric; v_id text; v_diff numeric; v_pct numeric; v_inspector text;
begin
  r := public._require_roles(array['state_admin','stock_inspector']::public.app_role[]);
  if _location_type not in ('godown', 'shop') then raise exception 'Location type must be godown or shop'; end if;
  if _measured_stock_kg is null or _measured_stock_kg < 0 then raise exception 'Measured stock must be zero or positive kg'; end if;
  perform public._check_location_access(r, _location_type, _location_id, 'record measurement for');
  if _location_type = 'godown' then
    select name into v_name from public.godowns where id = _location_id;
    v_expected := public.godown_stock(_location_id);
  else
    select name into v_name from public.shops where id = _location_id;
    v_expected := public.shop_stock(_location_id);
  end if;
  if v_name is null then raise exception 'Location ''%'' not found', _location_id; end if;
  select coalesce(full_name, username, 'Inspector') into v_inspector from public.profiles where id = auth.uid();
  v_id := public._next_id('MEA');
  insert into public.measurements(id, location_type, location_id, measured_date, measured_stock_kg, inspector_name, remarks)
  values (v_id, _location_type, _location_id, now(), round(_measured_stock_kg, 2), coalesce(v_inspector, 'Inspector'),
    coalesce(nullif(trim(coalesce(_remarks, '')), ''), 'Routine physical weighment audit'));
  v_diff := round(_measured_stock_kg - v_expected, 2);
  v_pct := case when v_expected > 0 then round(abs(v_diff) / v_expected * 100, 2) else 0 end;
  perform public._log_audit('RECORD_MEASUREMENT', upper(_location_type), _location_id,
    format('Physical stock audit %s logged by %s: measured %s kg vs expected %s kg (Variance: %s kg / %s%%).', v_id, v_inspector, round(_measured_stock_kg, 2), v_expected, v_diff, v_pct));
  return jsonb_build_object('measurement_id', v_id, 'expected_stock_kg', v_expected, 'variance_kg', v_diff, 'variance_pct', v_pct,
    'discrepancy_detected', v_pct > 2.0, 'message', format('Physical measurement %s recorded for %s.', v_id, v_name));
end $$;

-- ================= Alert engine =================
create or replace function public._has_open_alert(_type text, _loc text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.alerts where alert_type = _type and location_id = _loc and status in ('OPEN', 'UNDER_VERIFICATION'))
$$;

create or replace function public._scan_alerts()
returns jsonb language plpgsql security definer set search_path = public as $$
declare s record; d record; m record; v_new integer := 0; v_active integer; v_types jsonb;
begin
  for s in select * from public.v_shop_stock where status in ('LOW', 'CRITICAL') order by id loop
    if not public._has_open_alert('LOW_STOCK', s.id) then
      insert into public.alerts(id, location_type, location_id, item_id, alert_type, severity, explanation, assigned_role)
      values (public._next_id('ALT'), 'shop', s.id, 1, 'LOW_STOCK', case when s.status = 'CRITICAL' then 'CRITICAL' else 'HIGH' end,
        format('Closing stock of %s kg is %s of average monthly distribution (%s kg). Replenishment requested.',
          to_char(s.expected_stock_kg, 'FM999,999,990.00'), case when s.status = 'CRITICAL' then '< 10%' else '< 20%' end,
          to_char(s.avg_monthly_dist_kg, 'FM999,999,990.00')),
        'shop_manager');
      v_new := v_new + 1;
    end if;
  end loop;
  for d in select * from public.deliveries where status = 'DELAYED' order by id loop
    if not public._has_open_alert('DELAYED_DELIVERY', d.to_shop_id) then
      insert into public.alerts(id, location_type, location_id, alert_type, severity, explanation, assigned_role)
      values (public._next_id('ALT'), 'shop', d.to_shop_id, 'DELAYED_DELIVERY', 'MEDIUM',
        format('Consignment %s of %s kg dispatched from %s to %s is delayed past expected arrival date (%s). Route verification requested.',
          d.id, to_char(d.dispatched_qty_kg, 'FM999,999,990.00'), d.from_godown_id, d.to_shop_id, to_char(d.expected_delivery_date at time zone 'UTC', 'YYYY-MM-DD')),
        'godown_manager');
      v_new := v_new + 1;
    end if;
  end loop;
  for m in select * from public.v_measurement_reconciliation where discrepancy_detected order by measured_date desc loop
    if not public._has_open_alert('STOCK_DISCREPANCY', m.location_id) then
      insert into public.alerts(id, location_type, location_id, alert_type, severity, explanation, assigned_role)
      values (public._next_id('ALT'), m.location_type, m.location_id, 'STOCK_DISCREPANCY', case when m.difference_pct > 5.0 then 'HIGH' else 'MEDIUM' end,
        format('Verification requested on stock balance. Physical inspection %s recorded %s kg vs derived balance of %s kg (Variance: %s kg / %s%%, tolerance ±2.0%%). Routine ledger reconciliation requested.',
          m.measurement_id, to_char(m.measured_stock_kg, 'FM999,999,990.00'), to_char(m.expected_stock_kg, 'FM999,999,990.00'),
          to_char(m.difference_kg, 'FMS999,999,990.00'), m.difference_pct),
        'stock_inspector');
      v_new := v_new + 1;
    end if;
  end loop;
  for s in select sh.id from public.shops sh
    where not exists (select 1 from public.stock_movements mv where mv.location_id = sh.id and mv."timestamp" > timestamptz '2026-10-14 23:59:59+00')
    order by sh.id loop
    if not public._has_open_alert('MISSING_DATA', s.id) then
      insert into public.alerts(id, location_type, location_id, alert_type, severity, explanation, assigned_role)
      values (public._next_id('ALT'), 'shop', s.id, 'MISSING_DATA', 'MEDIUM',
        'No sales or movement activity logged for 10+ operational days. Data entry confirmation requested for shop register.',
        'data_entry_officer');
      v_new := v_new + 1;
    end if;
  end loop;
  select count(*) into v_active from public.alerts where status in ('OPEN', 'UNDER_VERIFICATION');
  select coalesce(jsonb_object_agg(alert_type, c), '{}'::jsonb) into v_types
    from (select alert_type, count(*) c from public.alerts where status in ('OPEN', 'UNDER_VERIFICATION') group by alert_type) t;
  return jsonb_build_object('new_alerts_created', v_new, 'total_active_alerts', v_active, 'alerts_by_type', v_types,
    'message', format('Scan complete: %s new alerts generated (%s active).', v_new, v_active));
end $$;

create or replace function public.scan_alerts()
returns jsonb language plpgsql security definer set search_path = public as $$
declare r public.user_roles; v jsonb;
begin
  r := public._require_roles(array['state_admin','district_officer','stock_inspector']::public.app_role[]);
  v := public._scan_alerts();
  perform public._log_audit('SCAN_ALERTS', 'SYSTEM', 'ALL', v->>'message');
  return v;
end $$;

create or replace function public.update_alert_status(_alert_id text, _new_status text, _notes text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r public.user_roles; a public.alerts; v_prefix text; v_uname text := public._actor_username();
begin
  r := public._require_roles(array['state_admin','district_officer','godown_manager','shop_manager','stock_inspector','data_entry_officer']::public.app_role[]);
  if _notes is null or trim(_notes) = '' then raise exception 'Verification notes are strictly required to update alert status'; end if;
  if _new_status not in ('OPEN', 'UNDER_VERIFICATION', 'RESOLVED') then raise exception 'Invalid status %', _new_status; end if;
  select * into a from public.alerts where id = _alert_id for update;
  if a.id is null then raise exception 'Alert ''%'' not found', _alert_id; end if;
  perform public._check_location_access(r, a.location_type, a.location_id, 'act on alert for');
  v_prefix := format('[%s by %s]: ', to_char(now() at time zone 'UTC', 'YYYY-MM-DD HH24:MI'), v_uname);
  update public.alerts set status = _new_status,
    verification_notes = case when verification_notes is null or verification_notes = '' then v_prefix || trim(_notes) else verification_notes || E'\n' || v_prefix || trim(_notes) end,
    resolution_date = case when _new_status = 'RESOLVED' then now() else resolution_date end
  where id = a.id;
  perform public._log_audit('UPDATE_ALERT_STATUS', 'ALERT', a.id,
    format('Alert %s (%s at %s) transitioned from %s to %s. Notes: %s', a.id, a.alert_type, a.location_id, a.status, _new_status, trim(_notes)));
  return jsonb_build_object('alert_id', a.id, 'old_status', a.status, 'new_status', _new_status,
    'message', format('Alert %s status changed to %s.', a.id, _new_status));
end $$;

-- ================= Forecast =================
create or replace function public.run_forecast(_shop_id text, _lookback integer default 4, _buffer_pct numeric default 10)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r public.user_roles; s public.shops; v_demands numeric[]; v_months text[]; v_pred numeric; v_buffer numeric; v_usable numeric;
  v_incoming numeric; v_pending text[]; v_rec numeric; v_id bigint;
begin
  r := public._require_roles(array['state_admin','district_officer','shop_manager']::public.app_role[]);
  perform public._check_location_access(r, 'shop', _shop_id, 'run forecast for');
  if _lookback not between 1 and 12 then raise exception 'Lookback must be between 1 and 12 months'; end if;
  select * into s from public.shops where id = _shop_id;
  if s.id is null then raise exception 'Shop ''%'' not found', _shop_id; end if;
  select array_agg(distributed_qty_kg order by month_year), array_agg(month_year order by month_year) into v_demands, v_months
  from (select * from public.monthly_distribution where shop_id = s.id order by month_year desc limit _lookback) t;
  if v_demands is null then raise exception 'No monthly distribution records found for shop ''%''', s.id; end if;
  v_pred := round((select avg(x) from unnest(v_demands) x), 2);
  v_buffer := round(v_pred * _buffer_pct / 100, 2);
  v_usable := public.shop_stock(s.id);
  select coalesce(sum(dispatched_qty_kg), 0), array_agg(id) into v_incoming, v_pending
    from public.deliveries where to_shop_id = s.id and status in ('PENDING', 'DELAYED');
  v_rec := greatest(0, round(v_pred + v_buffer - v_usable - v_incoming, 2));
  insert into public.predictions(shop_id, method, lookback_months, predicted_demand_kg, safety_buffer_kg, usable_stock_kg, planned_incoming_kg, recommended_replenishment_kg, inputs, created_by)
  values (s.id, 'rolling_average', array_length(v_demands, 1), v_pred, v_buffer, v_usable, v_incoming, v_rec,
    jsonb_build_object('months_evaluated', v_months, 'demands', v_demands, 'buffer_pct', _buffer_pct, 'pending_delivery_ids', coalesce(v_pending, '{}')),
    public._actor_username())
  returning id into v_id;
  perform public._log_audit('RUN_DEMAND_FORECAST', 'SHOP', s.id,
    format('Ran %s-mo demand forecast for %s. Demand: %s kg, Buffer: %s kg, Replenishment: %s kg. (Prediction #%s).', _lookback, s.id, v_pred, v_buffer, v_rec, v_id));
  return jsonb_build_object('prediction_id', v_id, 'predicted_demand_kg', v_pred, 'safety_buffer_kg', v_buffer, 'usable_stock_kg', v_usable,
    'planned_incoming_kg', v_incoming, 'recommended_replenishment_kg', v_rec, 'label', 'Planning recommendation, not an official allocation.');
end $$;

